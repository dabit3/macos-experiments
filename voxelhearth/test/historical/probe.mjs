import { chromium } from 'playwright';
import { Director, sleep } from './lib/director.mjs';
const d = new Director('ws://localhost:8787/ws');
await d.connect();
const browser = await chromium.launch({ channel: 'chrome', headless: false });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
page.on('console', (m) => { if (m.type() === 'error') console.log('[web]', m.text().split('\n')[0]); });
await page.goto('http://localhost:8787/?name=Probe&server=ws%3A%2F%2Flocalhost%3A8787%2Fws');
await sleep(3000);
const log = (l, r) => console.log(l.padEnd(14), JSON.stringify(r).slice(0, 160));
await d.must('Probe', { t: 'create_room', code: 'PROBE', seed: 1234, bots: 0, freezeTime: true, startTime: 6000 });
await d.must('Probe', { t: 'wait_screen', screen: 'lobby' });
await d.must('Probe', { t: 'start_match' });
await d.must('Probe', { t: 'wait_game' });
await sleep(1200);
const s = await d.drive('Probe', { t: 'state' });
log('state', s);
const fx = Math.floor(s.x), fz = Math.floor(s.z), fy = Math.floor(s.y);
// give some cobble into slot 4 and place a pillar 2 blocks ahead (+z)
log('give', await d.drive('Probe', { t: 'give', id: 9, count: 16, slot: 4 }));
await sleep(300);
log('select', await d.drive('Probe', { t: 'select_slot', slot: 4 }));
log('state.held', (await d.drive('Probe', { t: 'state' })).held);
log('place_at 1', await d.drive('Probe', { t: 'place_at', x: fx, y: fy, z: fz + 2 }));
log('place_at 2', await d.drive('Probe', { t: 'place_at', x: fx, y: fy + 1, z: fz + 2 }));
await sleep(400);
await page.screenshot({ path: '/tmp/vh-probe-placed.png' });
log('break 1', await d.drive('Probe', { t: 'break', x: fx, y: fy + 1, z: fz + 2 }));
await sleep(400);
await page.screenshot({ path: '/tmp/vh-probe-broken.png' });
log('break grass', await d.drive('Probe', { t: 'break', x: fx + 1, y: fy - 1, z: fz + 1 }));
log('chat', await d.drive('Probe', { t: 'chat', text: 'hello from probe' }));
await sleep(400);
const st = await d.drive('Probe', { t: 'state' });
log('state', st);
const h = await d.hashes('PROBE');
console.log('hashes', JSON.stringify(h));
const q = await d.query('PROBE');
console.log('query', JSON.stringify(q).slice(0,900));
await d.drive('Probe', { t: 'look_at', x: fx + 1, y: fy, z: fz });
await sleep(300);
await page.screenshot({ path: '/tmp/vh-probe-grass.png' });
await browser.close();
d.close();
